const productsGrid = document.getElementById("products-grid");

let cart = JSON.parse(localStorage.getItem("cart")) || {};


function saveCart() {
  localStorage.setItem("cart", JSON.stringify(cart));
}


function increaseQty(id, name, price, image) {
  if (!cart[id]) {
    cart[id] = { id, name, price, image, qty: 0 };
  }

  cart[id].qty += 1;
  saveCart();
  updateUI(id);
}


function decreaseQty(id) {
  if (!cart[id]) return;

  cart[id].qty -= 1;

  if (cart[id].qty <= 0) {
    delete cart[id];
  }

  saveCart();
  updateUI(id);
}


function updateUI(id) {
  const card = document.querySelector(`[data-id="${id}"]`);
  if (!card) return;

  const qtyEl = card.querySelector(".qty");

  if (cart[id]) {
    qtyEl.textContent = cart[id].qty;
  } else {
    qtyEl.textContent = 0;
  }
}


function displayProducts() {
  productsGrid.innerHTML = "";

  products.forEach(product => {
    const qty = cart[product.id] ? cart[product.id].qty : 0;

    const productCard = document.createElement("div");
    productCard.classList.add("product-card");
    productCard.setAttribute("data-id", product.id);

    productCard.innerHTML = `
      <img src="${product.image}" alt="${product.name}">
      <h3>${product.name}</h3>
      <p>Ksh ${product.price}</p>

      <div class="cart-controls">
        <button onclick="decreaseQty(${product.id})">-</button>
        <span class="qty">${qty}</span>
        <button onclick="increaseQty(${product.id}, '${product.name}', ${product.price}, '${product.image}')">+</button>
      </div>
    `;

    productsGrid.appendChild(productCard);
  });
}


displayProducts();